#!/usr/bin/env bash
# Stages a copy of the package that builds with the Command Line Tools alone
# (no Xcode), then prints the staged package path.
#
#   Scripts/stage-package.sh [ToolName=Scripts/ToolDir ...]
#
# `#Preview` needs the Previews macro plugin, which only ships with Xcode, so
# every `#Preview` block (always the last declaration in a file) is stripped.
# Each ToolName=dir argument adds an executable target built from dir/*.swift
# that depends on MotionLibrary and MotionGallery.
#
# The copy lives in .build/staging and is updated in place, so repeated builds
# stay incremental.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PKG="$ROOT/.build/staging"
mkdir -p "$PKG"

# Mirror Sources/, stripping previews. Only touch files whose content changed.
rm -rf "$PKG/Sources.next"
(cd "$ROOT" && find Sources -name '*.swift') | while read -r file; do
    mkdir -p "$(dirname "$PKG/Sources.next/${file#Sources/}")"
    awk '/^#Preview/{exit} {print}' "$ROOT/$file" > "$PKG/Sources.next/${file#Sources/}"
done
(cd "$ROOT" && find Sources -type f ! -name '*.swift') | while read -r file; do
    mkdir -p "$(dirname "$PKG/Sources.next/${file#Sources/}")"
    cp "$ROOT/$file" "$PKG/Sources.next/${file#Sources/}"
done

TARGETS=""
for tool in "$@"; do
    name="${tool%%=*}"
    dir="${tool#*=}"
    mkdir -p "$PKG/Sources.next/$name"
    cp "$ROOT/$dir"/*.swift "$PKG/Sources.next/$name/"
    TARGETS="$TARGETS        .executableTarget(name: \"$name\", dependencies: [\"MotionLibrary\", \"MotionGallery\"]),
"
done

mkdir -p "$PKG/Sources"
rsync -a --checksum --delete "$PKG/Sources.next/" "$PKG/Sources/"
rm -rf "$PKG/Sources.next"

cat > "$PKG/Package.swift.next" <<EOF
// swift-tools-version: 5.9
// Generated by Scripts/stage-package.sh. Do not edit.
import PackageDescription

let package = Package(
    name: "MotionLibraryStaging",
    platforms: [.macOS(.v14)],
    targets: [
        .target(name: "MotionLibrary"),
        .target(name: "MotionGallery", dependencies: ["MotionLibrary"]),
$TARGETS    ]
)
EOF
cmp -s "$PKG/Package.swift.next" "$PKG/Package.swift" 2>/dev/null \
    && rm "$PKG/Package.swift.next" \
    || mv "$PKG/Package.swift.next" "$PKG/Package.swift"

echo "$PKG"
